// Shared build helpers for the anatomy figures. Each figure module draws its
// static parts with these, marks its moving parts as slots, and calls finish().
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as k from '../../src/anatomy/kit/iso-kit.mjs'
import * as A from '../../src/anatomy/kit/audit.mjs'

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const argv = process.argv
const flag = (name) => {
  const i = argv.indexOf(name)
  return i > 0 ? argv[i + 1] : null
}

export function workshop(P) {
  const R = A.recorder(P)
  const S = (paths, style) => k.solidSvg(paths, style)
  const Ln = (d, style) => k.lineSvg(d, style)
  const Dots = (points, style) => k.dotsSvg(points, style)
  const at = (p) => k.iso(p, P)
  const seg = (a, b) => k.segment(a, b, P)
  const centre = (plan, z0, z1) => [plan.x + plan.w / 2, plan.y + plan.d / 2, (z0 + z1) / 2]
  const put = (name, ref, svg, shapes = [], extra = {}) => R.put({ name, at: ref, svg, shapes: shapes.map(R.solid), ...extra })
  // A rounded box standing on the floor: drawn, recorded, put.
  const box = (name, plan, z0, z1, style = {}, { steps = 3, bevel = 0, extra = '', inner, bias = 0 } = {}) =>
    put(name, centre(plan, z0, z1), S(k.slabOf(plan, z0, z1 - z0, P, steps, bevel), { tone: 'mid', ...style, inner: inner ?? style.inner }) + extra, [A.slab(plan, z0, z1 - z0, { name }, steps)], { bias })
  const ringScrews = (points, z, r = 0.9) =>
    Ln(points.map(([x, y]) => k.ring(x, y, r, z, P, 14)).join(''), { tone: 'lo' }) + Dots(points.map(([x, y]) => at([x, y, z])), { size: 0.42, tone: 'mid' })
  // A group drawn in the plane of a vertical face that looks along +y (local
  // coordinates are world x and -z) or along +x (local -y and -z).
  const facePlane = (y) => k.sideMatrix([0, y], 0, P, 'left')
  const facePlaneX = (x) => k.sideMatrix([x, 0], 0, P, 'right')
  return { R, S, Ln, Dots, at, seg, centre, put, box, ringScrews, facePlane, facePlaneX }
}

// Settle the order, keep moving parts beside the neighbours they need in
// every pose, audit, and write the generated module (and a preview page).
export function finish(R, P, { name, W, H, prefix = [], mustFollow = [], last = [], label, exports = {}, preview }) {
  A.settle(R, P)
  R.items.sort((a, b) => a.key - b.key)
  const index = (n) => R.items.findIndex((item) => item.name === n)
  for (const [later, earlier] of mustFollow) {
    const [a, b] = [index(later), index(earlier)]
    if (a < 0 || b < 0) throw new Error(`${name}: order check names a missing item: ${later} / ${earlier}`)
    if (a < b) {
      const [item] = R.items.splice(a, 1)
      R.items.splice(index(earlier) + 1, 0, item)
    }
  }
  for (const [later, earlier] of mustFollow) if (index(later) < index(earlier)) console.warn(`${name}: order still wrong:`, later, 'before', earlier)
  // Items drawn over everything, such as things in flight.
  for (const n of last) R.items.push(...R.items.splice(index(n), 1))
  // The audit reads keys, so make them follow the order actually drawn.
  R.items.forEach((item, i) => (item.key = i))

  if (argv.includes('--audit')) console.log(`\n== ${name} ==`)
  A.auditOrExit(R, P)

  const SEGMENTS = []
  let run = prefix.join('')
  for (const item of R.items) {
    if (item.slot) {
      SEGMENTS.push(run, { slot: item.slot })
      run = ''
    } else run += item.svg
  }
  SEGMENTS.push(run)

  const out = join(ROOT, `src/anatomy/${name}/art.generated.js`)
  const extra = Object.entries(exports).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)}\n`).join('')
  writeFileSync(out, `// Generated by scripts/build-anatomy.mjs. Do not edit by hand.\nexport const VIEW = ${JSON.stringify({ W, H })}\nexport const LABEL = ${JSON.stringify(label)}\n${extra}export const SEGMENTS = ${JSON.stringify(SEGMENTS)}\n`)
  const bytes = SEGMENTS.reduce((n, s) => n + (typeof s === 'string' ? s.length : 0), 0)
  console.log(`${name}: ${R.items.length} items · ${R.solids.length} solids · ${R.tubes.length} tubes · ${(bytes / 1024).toFixed(0)} KB of markup`)

  const dir = flag('--preview')
  if (dir && preview) {
    const { slots, plate } = preview()
    const body = SEGMENTS.map((s) => (typeof s === 'string' ? s : slots[s.slot] ?? '')).join('')
    const svg = k.figureSvg({ width: W, height: H, label, body })
    const css = readFileSync(join(ROOT, 'src/anatomy/anatomy.css'), 'utf8').replace(/@import[^;]+;/, '')
    const html = k.plateHtml({ ...plate, body: `<div class="iso-stage">${svg}</div>` })
    const file = join(dir, `${name}.html`)
    writeFileSync(file, k.pageHtml({ title: name, theme: 'dark', body: `<div class="bp-anatomy iso" data-theme="dark">${html}</div><style>${css}</style>`, width: 640 }))
    console.log(`${name}: preview ${file}`)
  }
  return SEGMENTS
}
